CREATE TRIGGER dbo.tr_Titular_InvalidarTop5 ON dbo.Titular WITH EXECUTE AS OWNER AFTER UPDATE AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(Latitud) OR UPDATE(Longitud) OR UPDATE(ProvinciaId)
 DELETE t FROM dbo.Top5 t JOIN inserted i ON i.CUIT=t.CUITPrincipal;
END;
GO
