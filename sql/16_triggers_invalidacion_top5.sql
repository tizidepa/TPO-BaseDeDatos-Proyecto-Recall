-- 16_triggers_invalidacion_top5: Invalidar sugerencias cuando cambian sus datos.
-- Ejecutar después de todos los archivos con número menor. Modo SQLCMD.
:ON ERROR EXIT
USE RecallsUADE;
GO
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
-- INICIO SECCION GENERADA
CREATE TRIGGER dbo.tr_Sucursal_InvalidarTop5 ON dbo.Sucursal WITH EXECUTE AS OWNER AFTER INSERT,UPDATE,DELETE AS
BEGIN SET NOCOUNT ON; DELETE FROM dbo.Top5; END;
GO
